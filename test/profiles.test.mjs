import { createProfiles } from '../src/profiles.mjs';
import { handleApi } from '../src/api.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs'; import crypto from 'node:crypto'; import os from 'node:os'; import path from 'node:path';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'prof-'));
const tag = (n) => ({ name: n, type: 'general' }), post = (...n) => ({ tags: n.map(tag), rating: 'explicit', type: 'image' });
const orig = { v: 1, enabled: true, prefs: { mode: 'comfort', media: 'all', blacklist: ['zzz'] }, votes: { 'rule34:1': { site: 'rule34', id: 1, vote: 1, t: Date.now(), pw: 1, rating: 'explicit', type: 'image', strat: null, tags: [['red', 'general']] } }, seen: {}, tagSeen: {}, nSeen: 0, bandit: {} };
fs.writeFileSync(path.join(dir, 'foryou.json'), JSON.stringify(orig));
const sha = () => { const d = JSON.parse(fs.readFileSync(path.join(dir, 'foryou.json'), 'utf8')); return crypto.createHash('sha256').update(JSON.stringify({ votes: d.votes, seen: d.seen, tagSeen: d.tagSeen, nSeen: d.nSeen })).digest('hex'); };
const before = sha();
let P = createProfiles({ dir }); let fy = P.current;
assert.equal(fy.state().likes, 1); assert.equal(fy.state().prefs.mode, 'comfort');
const id = P.create('Second'); assert.throws(() => P.create('second'), /exists/);
P.switchTo(id); assert.equal(P.current.state().likes, 0, 'new profile starts empty');
P.current.vote({ site: 'rule34', id: 50, vote: 1, post: post('blue') }); P.current.vote({ site: 'rule34', id: 51, vote: -1, post: post('green') });
P.current.markViewed({ site: 'rule34', id: 52, post: post('x') }); P.current.setPrefs({ whitelist: ['blue'] });
for (const e of [1]) P.flushAll(); await new Promise(r => setTimeout(r, 700)); P.flushAll();
assert.equal(sha(), before, 'default profile file is byte-for-byte unchanged');
assert(fs.existsSync(path.join(dir, `foryou-${id}.json`)));
P.switchTo('default'); assert.equal(P.current.state().likes, 1); assert.deepEqual(P.current.state().prefs.blacklist, ['zzz']);
assert.deepEqual(P.list().profiles.map(p => [p.name, p.likes, p.dislikes]), [['Default', 1, 0], ['Second', 1, 1]]);
P.current.setEnabled(false); P.switchTo(id); assert.equal(P.current.state().enabled, false); assert.throws(() => P.current.vote({ site: 'rule34', id: 60, vote: 1, post: post('a') }));
P.current.setEnabled(true);
P.flushAll(); await new Promise(r => setTimeout(r, 700)); P.flushAll();
let P2 = createProfiles({ dir }); assert.equal(P2.active, id); assert.equal(P2.current.state().likes, 1);
assert.throws(() => P2.remove('default'));
P2.current.setPrefs({ ignored: ['carry_me'], ignoreSpecies: true }); P2.switchTo('default');
assert(P2.current.state().prefs.ignored.includes('carry_me') && P2.current.state().prefs.ignoreSpecies === true, 'carried to Default');
assert.equal(P2.current.state().likes, 1);
P2.current.setPrefs({ ignored: ['carry_me'], ignoreSpecies: false }); P2.switchTo(id);
P2.remove(id);
assert.equal(P2.active, 'default'); assert.equal(P2.current.state().prefs.ignoreSpecies, false); assert(fs.readdirSync(dir).some(f => f.includes('.removed-')), 'data kept, not deleted'); assert.equal(P2.list().profiles.length, 1);
P2.flushAll();
const H = { 'x-goonpilot': '1', 'content-type': 'application/json' }, U = 'http://localhost:8787/api/foryou/';
const ctx = { foryou: P2.current, profiles: P2 };
const A = (p, o = {}) => handleApi(new Request(U + p, { headers: H, ...o }), {}, fetch, ctx);
assert.equal((await handleApi(new Request(U + 'profiles'), {}, fetch, ctx)).status, 403);
let r = await (await A('profile', { method: 'POST', body: JSON.stringify({ action: 'create', name: 'Third', switch: true }) })).json(); assert.equal(r.active, r.id);
assert.equal((await A('profile', { method: 'POST', body: JSON.stringify({ action: 'delete', id: 'default', confirm: true }) })).status, 400);
assert.equal((await A('profile', { method: 'POST', body: JSON.stringify({ action: 'delete', id: r.id }) })).status, 400);
const st = await (await A('state')).json(); assert.equal(st.profileList.profiles.length, 2);
P2.flushAll(); console.log('PROFILES OK');
